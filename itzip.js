  // Coalesce bursts of DOM changes into one pass on the next frame.
  var queued = false;
  function schedule(){
    if (queued) return;
    queued = true;
    var raf = window.requestAnimationFrame || function (f) { return setTimeout(f, 16); };
    raf(function () { queued = false; tickTidy(); });
  }

