/* ===== core-6-campaign-guard.js ===== */
// Shared by both sites: the campaign list page lives on the FitTalk company site today and the
// ItZip site keeps the same guard, so the path comes from campaignPath in the brand file.
(function () {
  var CAMPAIGN_PATH = (window.FIT_BRAND || {}).campaignPath || '/about';
  var KEY = 'fitCampaignReloaded';
  var ready = false;
  var seenAway = location.pathname.indexOf(CAMPAIGN_PATH) !== 0;
  setTimeout(function () { ready = true; }, 1500);
  function guard() {
    if (location.pathname.indexOf(CAMPAIGN_PATH) !== 0) {
      seenAway = true;
      try { sessionStorage.removeItem(KEY); } catch (e) {}   // left the page, arm it again
      return;
    }
    if (!seenAway) return;                                   // original full load: widget handles it
    if (!ready) return;                                      // too early to judge on a full load
    if (window.FIT_CAMPAIGN_READY) return;                   // widget script ran, list is being built
    if (document.querySelector('#ftclGrid .ftcl-card')) return; // list already on screen
    try {
      if (sessionStorage.getItem(KEY)) return;               // already reloaded once, do not loop
      sessionStorage.setItem(KEY, '1');
    } catch (e) { return; }                                  // no sessionStorage, never risk a loop
    location.reload();
  }
  function wrap(name) {
    var orig = history[name];
    if (!orig) return;
    history[name] = function () {
      var r = orig.apply(this, arguments);
      guard();                                               // run at once so the wrong view barely shows
      return r;
    };
  }
  wrap('pushState');
  wrap('replaceState');
  window.addEventListener('popstate', guard);
  setInterval(guard, 200);                                   // catches navigations the hooks above miss
})();

/* ===== core-5-autofit.js ===== */
(function () {
  var CFG = {
    include: '[data-type="code"] iframe',
    excludeSrc: ['banner', 'bnDress', 'youtube', 'ads', 'pay', 'checkout']  // secondary safety net
  };

  var seen = new WeakMap();         // iframe -> last applied height and ratio

  function isExcluded(fr) {
    var s = ((fr.getAttribute('src') || 0) + ' ' + (fr.id || 0) + ' ' + (fr.className || 0)).toLowerCase();
    for (var i = 0; i < CFG.excludeSrc.length; i++) {
      if (s.indexOf(CFG.excludeSrc[i].toLowerCase()) !== -1) return true;
    }
    return false;
  }

  // Qshop draws the whole page as one canvas and scales it: --site-ratio is the factor.
  // There are two canvases - desktop is drawn at 1280px, mobile at 374px - and whichever
  // applies gets stretched to fill the window. A 1024 tablet is the desktop canvas at 0.8,
  // a 768 tablet is the MOBILE canvas blown up to 2.05. Section heights, fonts and images
  // all follow that factor. A code widget is the only thing that does not, because it
  // lives in an iframe with its own viewport: at 0.8 it draws too big and covers the next
  // section, at 2.05 it draws a phone-sized widget in a section built for 2x and leaves a
  // screen of white space. Same bug, both directions.
  function siteRatio() {
    var v = parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--site-ratio'));
    return (v > 0.05 && v < 20) ? v : 1;
  }

  function plain(R) { return Math.abs(R - 1) < 0.02; }

  // Lay the widget out at the width its canvas was drawn at, then scale the result -
  // exactly what Qshop does with everything else on the page.
  function applyScale(fr, R) {
    if (plain(R)) {
      if (fr.style.transform) {
        fr.style.removeProperty('width');
        fr.style.removeProperty('transform');
        fr.style.removeProperty('transform-origin');
        fr.style.removeProperty('flex-shrink');
      }
      return;
    }
    var want = 'scale(' + R + ')';
    if (fr.style.transform === want) return;
    fr.style.flexShrink = '0';   // the iframe is a flex item: without this it shrinks straight back
    fr.style.width = (100 / R) + '%';
    fr.style.transformOrigin = 'top left';
    fr.style.transform = want;
  }

  function innerHeight(doc) {
    var b = doc.body, e = doc.documentElement;
    return Math.max(
      b ? b.scrollHeight : 0, b ? b.offsetHeight : 0,
      e ? e.scrollHeight : 0, e ? e.offsetHeight : 0
    );
  }

  // scrollHeight ratchets: once we made the iframe tall, the document inside can never
  // report anything smaller, so a widget that becomes shorter (window widened, cards back
  // on one row) would keep the old height forever. Where the bottom of the last child is
  // clearly higher than that, trust the children instead - that number can go down.
  function contentHeight(doc) {
    var b = doc.body, win = doc.defaultView;
    if (!b || !win) return 0;
    var top = b.getBoundingClientRect().top, max = 0, kids = b.children;
    for (var i = 0; i < kids.length; i++) {
      var c = kids[i], tag = c.tagName;
      if (tag === 'SCRIPT' || tag === 'STYLE' || tag === 'LINK') continue;
      var cs = win.getComputedStyle(c);
      if (cs.display === 'none' || cs.position === 'fixed') continue;
      var bottom = c.getBoundingClientRect().bottom - top + (parseFloat(cs.marginBottom) || 0);
      if (bottom > max) max = bottom;
    }
    if (max <= 0) return 0;
    return Math.round(max + (parseFloat(win.getComputedStyle(b).paddingBottom) || 0));
  }

  function measure(doc) {
    var h = innerHeight(doc), c = contentHeight(doc);
    return (c > 0 && c < h - 8) ? c : h;   // only the shrink direction needs the child walk
  }

  function codeSlot(fr) {
    var el = fr.parentNode, hops = 0;
    while (el && el.nodeType === 1 && hops < 6) {
      if (el.getAttribute && el.getAttribute('data-type') === 'code') return el;
      el = el.parentNode; hops++;
    }
    return null;
  }

  // Last line of defence. A widget that still needs more room than its slot does not push
  // anything down - it just paints over the section below. Grow the section by whatever
  // hangs out the bottom so the page stays stacked instead of overlapping.
  function guard(fr) {
    var slot = codeSlot(fr);
    if (!slot) return;
    var grid = slot.parentNode;
    if (!grid || grid.nodeType !== 1 || !window.getComputedStyle) return;
    var gcs = window.getComputedStyle(grid);
    if (gcs.display.indexOf('grid') === -1) return;

    if (grid.__ftPad === undefined) grid.__ftPad = parseFloat(gcs.paddingBottom) || 0;
    grid.style.paddingBottom = grid.__ftPad + 'px';      // measure without our own padding

    var bottom = grid.getBoundingClientRect().bottom, over = 0, kids = grid.children;
    for (var i = 0; i < kids.length; i++) {
      var d = kids[i].getBoundingClientRect().bottom - bottom;
      if (d > over) over = d;
    }
    if (over > 1) grid.style.paddingBottom = (grid.__ftPad + Math.ceil(over)) + 'px';
  }

  function fit(fr) {
    if (isExcluded(fr)) return;
    var doc;
    try { doc = fr.contentDocument; } catch (e) { return; }   // cross-origin -> skip
    if (!doc || !doc.body) return;

    var R = siteRatio();
    applyScale(fr, R);          // width first, so the height below is measured on it

    var h = measure(doc);
    if (h <= 0) return;

    var key = h + 'x' + R;
    if (seen.get(fr) !== key) {
      seen.set(fr, key);

      fr.style.height = h + 'px';
      fr.style.minHeight = '0';
      fr.style.maxHeight = 'none';
      fr.style.overflow = 'hidden';
      // scale() is paint only - the box still takes h px of the page, so hand the rest
      // over (or give it back, when R is below 1) through the margin.
      if (plain(R)) fr.style.removeProperty('margin-bottom');
      else fr.style.marginBottom = Math.round(h * (R - 1)) + 'px';
      fr.setAttribute('scrolling', 'no');
      try { doc.documentElement.style.overflow = 'hidden'; doc.body.style.overflow = 'hidden'; } catch (e) {}

      unlockChain(fr);   // release fixed height so the grid row grows and pushes siblings down
    }

    guard(fr);           // the slot itself never grows, so give the section room for the spill
  }

  function unlockChain(fr) {
    var el = fr.parentNode, hops = 0;
    while (el && el.nodeType === 1 && hops < 6) {
      el.style.height = 'auto';
      el.style.minHeight = '0';
      el.style.maxHeight = 'none';
      el.style.overflow = 'visible';
      if (el.getAttribute && el.getAttribute('data-type') === 'code') {
        el.style.alignSelf = 'start';   // sit at top of the cell and grow with content
        break;
      }
      el = el.parentNode; hops++;
    }
  }

  function targets() {
    return CFG.include ? document.querySelectorAll(CFG.include) : document.getElementsByTagName('iframe');
  }

  function fitAll() {
    var list = targets();
    for (var i = 0; i < list.length; i++) fit(list[i]);
  }

  function hook(fr) {
    var doc;
    try { doc = fr.contentDocument; } catch (e) { return; }
    if (!doc || !doc.body) return;
    if (window.ResizeObserver && !doc.__ftRO) {
      doc.__ftRO = new ResizeObserver(function () { fit(fr); });
      doc.__ftRO.observe(doc.documentElement);
      doc.__ftRO.observe(doc.body);
    }
  }

  function watch(fr) {
    if (seen.has(fr)) return;
    seen.set(fr, 0);
    fr.addEventListener('load', function () { hook(fr); fit(fr); });
    hook(fr); fit(fr);
  }

  function scan() {
    var list = targets();
    for (var i = 0; i < list.length; i++) watch(list[i]);
  }

  window.addEventListener('resize', fitAll);
  window.addEventListener('load', function () { scan(); fitAll(); });
  document.addEventListener('DOMContentLoaded', scan);
  [100, 400, 900, 1800, 3000].forEach(function (t) { setTimeout(function () { scan(); fitAll(); }, t); });

  try {
    new MutationObserver(function () { scan(); }).observe(
      document.documentElement, { childList: true, subtree: true }
    );
  } catch (e) {}

  window.addEventListener('message', function (e) {
    var d = e.data;
    if (!d || d.type !== 'ftEmbedHeight') return;
    var list = document.getElementsByTagName('iframe');
    for (var i = 0; i < list.length; i++) {
      if (list[i].contentWindow === e.source) {
        list[i].style.height = d.height + 'px';
        list[i].style.overflow = 'hidden';
        list[i].setAttribute('scrolling', 'no');
        guard(list[i]);
        break;
      }
    }
  });

  scan();
})();

