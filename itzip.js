/* ===== core-2-scroll.js ===== */
(function () {
  var FIT_SMOOTH = true;
  var EASE = 0.12;
  if (!FIT_SMOOTH) return;
  var mm = window.matchMedia;
  if (mm && mm('(prefers-reduced-motion: reduce)').matches) return; // user asked the OS to reduce motion
  if (mm && mm('(pointer: coarse)').matches) return;                // touch / mobile: leave native scroll alone
  if (!window.requestAnimationFrame) return;
  var target = window.pageYOffset || 0, current = target, raf = 0, busy = false, lastSet = -1;
  function maxY() { return Math.max(0, (document.documentElement.scrollHeight || 0) - window.innerHeight); }
  function loop() {
    var d = target - current;
    if (Math.abs(d) < 0.5) { current = target; lastSet = Math.round(current); window.scrollTo(0, lastSet); raf = 0; busy = false; return; }
    current += d * EASE;
    lastSet = Math.round(current);
    window.scrollTo(0, lastSet);
    raf = window.requestAnimationFrame(loop);
  }
  // Walk up from the wheel target looking for a nested scroller (modal bodies, policy
  // boxes, code blocks) that can still move in the requested direction. If we find one,
  // let the browser handle it natively instead of hijacking the page scroll.
  function innerScroller(node, dy) {
    while (node && node.nodeType === 1 && node !== document.body && node !== document.documentElement) {
      var oy = window.getComputedStyle(node).overflowY;
      if ((oy === 'auto' || oy === 'scroll' || oy === 'overlay') && node.scrollHeight > node.clientHeight + 1) {
        if (dy < 0 ? node.scrollTop > 0 : node.scrollTop + node.clientHeight < node.scrollHeight - 1) return node;
      }
      node = node.parentNode;
    }
    return null;
  }
  window.addEventListener('wheel', function (e) {
    if (e.ctrlKey) return;                       // pinch-zoom: do not interfere
    if (innerScroller(e.target, e.deltaY)) return;
    e.preventDefault();
    var step = e.deltaY;
    if (e.deltaMode === 1) step *= 16;           // line units to approx pixels
    else if (e.deltaMode === 2) step *= window.innerHeight;
    target = Math.max(0, Math.min(maxY(), target + step));
    busy = true;
    if (!raf) raf = window.requestAnimationFrame(loop);
  }, { passive: false });
  window.addEventListener('scroll', function () {
    if (!busy) { target = current = window.pageYOffset; return; }
    if (lastSet >= 0 && Math.abs(window.pageYOffset - lastSet) > 2) {
      target = current = window.pageYOffset; busy = false;
      if (raf) { window.cancelAnimationFrame(raf); raf = 0; }
    }
  }, { passive: true });
  window.addEventListener('resize', function () { target = Math.min(target, maxY()); });
})();

